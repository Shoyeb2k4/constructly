/**
 * WCAG contrast helpers (pure). Brand colors are used as solid backgrounds with
 * white text (buttons, badges), so we validate each against white.
 */

export const WHITE = "#ffffff";

/** Minimum ratio to allow saving (WCAG AA for UI/large text). */
export const MIN_CONTRAST = 3;
/** Recommended ratio (WCAG AA for normal text). */
export const GOOD_CONTRAST = 4.5;

function hexToRgb(hex: string): [number, number, number] | null {
  const m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex);
  if (!m) return null;
  return [parseInt(m[1], 16), parseInt(m[2], 16), parseInt(m[3], 16)];
}

function linearize(v: number): number {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
}

export function relativeLuminance(hex: string): number {
  const rgb = hexToRgb(hex);
  if (!rgb) return 0;
  const [r, g, b] = rgb.map(linearize);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG contrast ratio between two colors (1–21). */
export function contrastRatio(a: string, b: string): number {
  const la = relativeLuminance(a);
  const lb = relativeLuminance(b);
  const hi = Math.max(la, lb);
  const lo = Math.min(la, lb);
  return (hi + 0.05) / (lo + 0.05);
}

/** Contrast of a brand color against white text. */
export function contrastOnWhite(color: string): number {
  return contrastRatio(color, WHITE);
}
